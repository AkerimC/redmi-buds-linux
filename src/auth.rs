/// Bit `i` set => xor, and substitution table A; clear => add, table B.
const XOR_MASK: u16 = 0x9999;

#[inline]
fn rol8(b: u8, n: u32) -> u8 {
    b.rotate_left(n)
}

#[inline]
fn sel(i: usize) -> bool {
    (1u16 << i) & XOR_MASK != 0
}

/// Expand a 16-byte key into the 272-byte round schedule (vendor `sub_1630`).
pub fn expand_key(key: &[u8; 16]) -> [u8; 272] {
    let mut buf = [0u8; 272];
    buf[..16].copy_from_slice(key);

    // Seed checksum: XOR of the eight high/low byte differences.
    let mut checksum: u8 = 0;
    for i in 0..8 {
        checksum ^= key[i] ^ key[i + 8];
    }

    let mut state = *key;
    for r in 0..16usize {
        for b in state.iter_mut() {
            *b = rol8(*b, 3);
        }
        checksum = rol8(checksum, 3);

        // 17-byte rolling window: rotated state plus the checksum byte.
        let mut window = [0u8; 17];
        window[..16].copy_from_slice(&state);
        window[16] = checksum;

        let table_base = r * 16;
        let out_base = 16 + r * 16; // the key stays at buf[..16]
        for j in 0..16usize {
            buf[out_base + j] =
                TAB_EXPAND[table_base + 15 - j].wrapping_add(window[(r + 1 + j) % 17]);
        }
    }
    buf
}

