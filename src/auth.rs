/// The 8-round mixing network (vendor `sub_176c`).
fn mix(state: &mut [u8; 16], sched: &[u8; 272], flag: bool) {
    let orig = *state;
    let mut out = *state;

    for rnd in 0..8usize {
        let base = rnd * 32;

        if flag && rnd == 2 {
            for i in 0..16 {
                out[i] = if sel(i) {
                    out[i] ^ orig[i]
                } else {
                    out[i].wrapping_add(orig[i])
                };
            }
        }

        // First sched pass: xor where the mask bit is set.
        for i in 0..16 {
            let v = sched[base + i];
            out[i] = if sel(i) { out[i] ^ v } else { out[i].wrapping_add(v) };
        }

        // Substitution: mask set -> table A, clear -> table B.
        for i in 0..16 {
            out[i] = if sel(i) { TAB_A[out[i] as usize] } else { TAB_B[out[i] as usize] };
        }

        // Second sched pass: add where the mask bit is set (opposite sense).
        for i in 0..16 {
            let v = sched[base + 16 + i];
            out[i] = if sel(i) { out[i].wrapping_add(v) } else { out[i] ^ v };
        }

        out = round16(&out);
    }

    // Final combine with sched[256..272].
    for i in 0..16 {
        let v = sched[0x100 + i];
        out[i] = if sel(i) { out[i] ^ v } else { out[i].wrapping_add(v) };
    }

    *state = out;
}

/// The 16-byte auth response for a 16-byte challenge.
pub fn transform(addr6: &[u8; 6], challenge: &[u8; 16]) -> [u8; 16] {
    let mut out = [0u8; 16];
    out[..6].copy_from_slice(addr6);
    out[6..12].copy_from_slice(addr6);
    out[12..].copy_from_slice(&addr6[..4]);

    let mut tmp = *challenge;
    tmp[15] ^= 0x06;

    let sched = expand_key(&tmp);
    mix(&mut out, &sched, true);
    out
}

