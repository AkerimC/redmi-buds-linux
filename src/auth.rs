pub fn hex_decode(s: &str) -> Option<Vec<u8>> {
    let s: Vec<u8> = s.bytes().filter(|c| !c.is_ascii_whitespace()).collect();
    if !s.len().is_multiple_of(2) {
        return None;
    }
    let val = |c: u8| -> Option<u8> {
        match c {
            b'0'..=b'9' => Some(c - b'0'),
            b'a'..=b'f' => Some(c - b'a' + 10),
            b'A'..=b'F' => Some(c - b'A' + 10),
            _ => None,
        }
    };
    let mut out = Vec::with_capacity(s.len() / 2);
    for pair in s.chunks(2) {
        out.push((val(pair[0])? << 4) | val(pair[1])?);
    }
    Some(out)
}

pub fn hex_encode(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_answers_from_hardware() {
        for (chal, want) in KNOWN_ANSWERS.iter() {
            let c: [u8; 16] = hex_decode(chal).unwrap().try_into().unwrap();
            let got = hex_encode(&transform(&ADDR6_PLACEHOLDER, &c));
            assert_eq!(got, *want, "challenge {chal}");
        }
    }

    #[test]
    fn expansion_round_trip_shape() {
        let sched = expand_key(&[0u8; 16]);
        assert_eq!(&sched[..16], &[0u8; 16]); // key stays at the front
        assert!(sched[16..].iter().any(|&b| b != 0));
    }
}
