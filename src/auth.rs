//! Xiaomi/JieLi auth transform.
//!
//! Direct port of `xiaomi_auth.py`, recovered from
//! the app's `libxm_bluetooth.so`. No vendor library, emulator or external
//! crate is involved.
//!
//! The vendor `function_xiaomi` calls `function_E1test` and then `function_E21`;
//! because E21 overwrites the output buffer before mixing, the E1test result is
//! unreachable and the whole transform is exactly E21:
//!
//! ```text
//! out   = addr6 || addr6 || addr6[..4]
//! tmp   = challenge ; tmp[15] ^= 0x06
//! sched = expand_key(tmp)
//! out   = mix(out, sched, flag = true)
//! ```
//!
//! All arithmetic below is mod 256, which the original 32-bit code truncates to
//! via its byte stores.

